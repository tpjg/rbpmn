//! Rendering the results this machine has measured into a markdown
//! comparison table.
//!
//! The renderer's job is not to make numbers look good — it is to make them
//! impossible to quote without their conditions. Every table is grouped by
//! host, because two rows measured on different machines are not comparable
//! and putting them adjacent implies that they are; every row carries its
//! history level, worker counts and Postgres provisioning; and anything a
//! run warned about is printed under the table rather than dropped.

use crate::result::RunResult;
use std::collections::BTreeMap;
use std::path::Path;

pub fn render(root: &Path) -> Result<String, String> {
    let dir = root.join("results");
    let mut paths: Vec<std::path::PathBuf> = match std::fs::read_dir(&dir) {
        Ok(entries) => entries
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|ext| ext == "json"))
            .collect(),
        Err(e) => return Err(format!("{}: {e}", dir.display())),
    };
    paths.sort();

    let mut runs: Vec<RunResult> = Vec::new();
    let mut skipped: Vec<String> = Vec::new();
    for path in &paths {
        let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        // Micro baselines live in `.baselines/`, not here — but a persisted
        // micro report does share this directory, and so might a result from
        // a future schema. Skip loudly rather than failing the render.
        match serde_json::from_str::<RunResult>(&text) {
            Ok(run) => runs.push(run),
            Err(_) => skipped.push(
                path.file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_default(),
            ),
        }
    }

    if runs.is_empty() {
        return Err(format!(
            "no lifecycle results in {} — run `just bench` first",
            dir.display()
        ));
    }

    let mut out = String::from("# rbpmn benchmark results\n\n");
    out.push_str(
        "Generated by `just bench-report`. **These numbers are not comparable with \
         published Camunda or Flowable figures** — different workload shapes, different \
         hardware, different history settings. They are not comparable across the host \
         sections below either. See `benchmarks/README.md`.\n\n",
    );

    let mut by_host: BTreeMap<String, Vec<&RunResult>> = BTreeMap::new();
    for run in &runs {
        by_host
            .entry(run.hardware.host_id.clone())
            .or_default()
            .push(run);
    }

    for (host, runs) in &by_host {
        let first = runs[0];
        let detected = &first.hardware.detected;
        out.push_str(&format!("## Host `{host}`\n\n"));
        out.push_str(&format!(
            "{} · {} physical cores · {} GB RAM · {} {} · disk: {} · Postgres: {}\n\n",
            detected.cpu_model,
            detected
                .physical_cores
                .map(|c| c.to_string())
                .unwrap_or_else(|| "?".into()),
            detected
                .ram_gb
                .map(|g| format!("{g:.0}"))
                .unwrap_or_else(|| "?".into()),
            detected.os,
            detected.arch,
            first
                .hardware
                .declared
                .as_ref()
                .map(|d| d.disk.clone())
                .unwrap_or_else(|| "undeclared".into()),
            short_version(&first.postgres.version),
        ));

        out.push_str(
            "| Scenario | Mode | History | Instances | Duration | Throughput (inst/s) | \
             p50 (ms) | p95 (ms) | p99 (ms) | Latency from | Workers | Events/inst | Date |\n\
             |---|---|---|---|---:|---:|---:|---:|---:|---|---|---:|---|\n",
        );
        for run in runs {
            let m = &run.measurements;
            out.push_str(&format!(
                "| `{}` | {} | {} | {} | {:.1}s | **{:.1}** | {:.1} | {:.1} | {:.1} | {} | \
                 {}s/{}u/{}c | {:.1} | {} |\n",
                run.scenario,
                run.mode,
                run.history,
                m.completed_instances,
                m.duration_secs,
                m.throughput_instances_per_sec,
                m.latency_ms.p50,
                m.latency_ms.p95,
                m.latency_ms.p99,
                m.latency_kind,
                run.harness.service_workers,
                run.harness.user_workers,
                run.harness.correlators,
                m.events_per_instance,
                run.started_at.get(..10).unwrap_or(""),
            ));
        }
        out.push('\n');

        out.push_str("<details>\n<summary>Conditions</summary>\n\n");
        for run in runs {
            out.push_str(&format!(
                "**`{}`** — {}\n\n",
                run.scenario, run.scope.summary
            ));
            out.push_str("Measures:\n");
            for line in &run.scope.measures {
                out.push_str(&format!("- {line}\n"));
            }
            out.push_str("\nDoes **not** measure:\n");
            for line in &run.scope.excludes {
                out.push_str(&format!("- {line}\n"));
            }
            out.push_str(&format!(
                "\nrbpmn `{}`{} · seed {} · pool {} · {} · {}\n\n",
                run.checkout
                    .git_sha
                    .as_deref()
                    .map(|s| &s[..s.len().min(8)])
                    .unwrap_or("unknown"),
                if run.checkout.dirty { " (dirty)" } else { "" },
                run.provenance.seed,
                run.harness.db_pool,
                if run.postgres.local {
                    "database local"
                } else {
                    "database remote"
                },
                run.postgres.provisioned_by,
            ));
            if !run.warnings.is_empty() {
                out.push_str("Warnings:\n");
                for warning in &run.warnings {
                    out.push_str(&format!("- {warning}\n"));
                }
                out.push('\n');
            }
            if run.measurements.backpressure.occurred {
                out.push_str(&format!(
                    "Backpressure: {}\n\n",
                    run.measurements.backpressure.reason
                ));
            }
        }
        out.push_str("</details>\n\n");
    }

    out.push_str(
        "## The history axis\n\n\
         Every run above is `history = full`: the engine writes every event, which is the \
         only configuration that exists (per-definition event-kind filtering is a roadmap \
         item — see `benchmarks/README.md`). The `Events/inst` column is what the \
         benchmark can honestly say about the lever today: how much history each instance \
         generates.\n\n",
    );

    if !skipped.is_empty() {
        out.push_str(&format!(
            "## Skipped files\n\nNot lifecycle results (different schema or shape): {}\n\n",
            skipped
                .iter()
                .map(|s| format!("`{s}`"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    Ok(out)
}

/// `PostgreSQL 17.5 (Debian ...)` → `17.5`.
fn short_version(version: &str) -> String {
    version
        .split_whitespace()
        .nth(1)
        .unwrap_or(version)
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_version_string_shortens() {
        assert_eq!(
            short_version("PostgreSQL 17.5 (Debian 17.5-1.pgdg120+1) on aarch64"),
            "17.5"
        );
        assert_eq!(short_version("weird"), "weird");
    }
}
