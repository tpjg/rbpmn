// Generates src/fixtures.generated.js from the Rust fixture corpus — the
// single source of truth. Runs automatically before dev/build (npm pre-hooks).
import { existsSync, readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixturesRoot = join(here, '..', '..', 'crates', 'rbpmn-model', 'tests', 'fixtures');
const outFile = join(here, '..', 'src', 'fixtures.generated.js');

export function parseExpectations(xml) {
  const start = xml.indexOf('expect-diagnostics:');
  if (start < 0) return null;
  const rest = xml.slice(start + 'expect-diagnostics:'.length);
  const end = rest.indexOf('-->');
  return rest
    .slice(0, end)
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const [severity, rule, at, element] = line.split(/\s+/);
      if (at !== '@') throw new Error(`bad expectation line: ${line}`);
      return { severity, rule, element };
    });
}

export function loadFixtures() {
  const fixtures = {};
  const expected = {};
  const bindings = {};
  for (const dir of ['accept', 'reject']) {
    for (const file of readdirSync(join(fixturesRoot, dir))
      .filter((f) => f.endsWith('.bpmn'))
      .sort()) {
      const name = `${dir}/${file}`;
      const xml = readFileSync(join(fixturesRoot, dir, file), 'utf8');
      fixtures[name] = xml;
      expected[name] = parseExpectations(xml);
      // A `.bpmn` is half a deployment. Where the corpus writes the other
      // half down beside it, parity feeds it — otherwise `check_deployable`
      // would be compared with an empty manifest for every fixture, and the
      // whole manifest half of L2 (topics, correlations, decisions, config)
      // would never be compared between the two builds at all.
      const sidecar = join(fixturesRoot, dir, file.replace(/\.bpmn$/, '.bindings.json'));
      bindings[name] = existsSync(sidecar) ? readFileSync(sidecar, 'utf8').trim() : '{}';
    }
  }
  return { fixtures, expected, bindings };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { fixtures, expected } = loadFixtures();
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(
    outFile,
    `// GENERATED by scripts/gen-fixtures.mjs — do not edit.\n` +
      `export const FIXTURES = ${JSON.stringify(fixtures, null, 1)};\n` +
      `export const EXPECTED = ${JSON.stringify(expected, null, 1)};\n`
  );
  console.log(`generated ${Object.keys(fixtures).length} fixtures -> src/fixtures.generated.js`);
}
